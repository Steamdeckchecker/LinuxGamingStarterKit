"""Generate one dependency-free Worker with the existing site assets embedded."""
from pathlib import Path
import base64
import json
import mimetypes
import struct
import zipfile

root = Path(__file__).resolve().parents[1]
assets = {}
types = {'.desktop': 'application/x-desktop', '.sh': 'text/x-shellscript; charset=utf-8', '.txt': 'text/plain; charset=utf-8', '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.xml': 'application/xml; charset=utf-8'}
for path in sorted((root / 'public').rglob('*')):
    if path.is_file():
        name = '/' + path.relative_to(root / 'public').as_posix()
        content_type = types.get(path.suffix, mimetypes.guess_type(path.name)[0] or 'application/octet-stream')
        assets[name] = {'type': content_type, 'data': base64.b64encode(path.read_bytes()).decode('ascii')}
snapshot = json.loads((root / 'latest-videos.json').read_text())
# Reuse stored source-ZIP members for standalone downloads and project icons
# instead of embedding a second full copy in the Worker.
for bundle in (root / 'public/downloads').glob('Linux-Handheld-Starter-Kit-v*.zip'):
    with zipfile.ZipFile(bundle) as archive:
        for item in archive.infolist():
            relative = Path(*Path(item.filename).parts[1:])
            if relative.parts[0] == 'assets' and relative.suffix == '.png':
                key = '/assets/' + relative.name
            elif len(relative.parts) == 1 or relative.suffix == '.zip':
                key = '/downloads/' + relative.name
            else:
                continue
            standalone = root / 'public' / key.lstrip('/')
            if not standalone.is_file():
                continue
            if item.compress_type != zipfile.ZIP_STORED:
                continue
            if archive.read(item) != standalone.read_bytes():
                raise ValueError('Bundled download differs: ' + item.filename)
            with bundle.open('rb') as stream:
                stream.seek(item.header_offset)
                header = stream.read(30)
            name_length, extra_length = struct.unpack_from('<HH', header, 26)
            offset = item.header_offset + 30 + name_length + extra_length
            assets[key] = {'type': assets[key]['type'],
                           'archive': '/downloads/' + bundle.name,
                           'offset': offset, 'length': item.file_size}
runtime = (root / 'worker/runtime.js').read_text()
(root / 'worker/index.js').write_text('// Generated by scripts/embed-assets.py; edit worker/runtime.js or public assets.\n' + runtime + '\nconst ASSETS = ' + json.dumps(assets, separators=(',', ':')) + ';\nconst SNAPSHOT = ' + json.dumps(snapshot, ensure_ascii=False) + ';\nexport default createWorker(ASSETS, SNAPSHOT);\n')
print(f'Embedded {len(assets)} assets in the Site Worker.')
