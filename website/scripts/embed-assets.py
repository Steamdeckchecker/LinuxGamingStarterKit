"""Generate one dependency-free Worker with the existing site assets embedded."""
from pathlib import Path
import base64
import json
import mimetypes

root = Path(__file__).resolve().parents[1]
assets = {}
types = {'.desktop': 'application/x-desktop', '.sh': 'text/x-shellscript; charset=utf-8', '.txt': 'text/plain; charset=utf-8', '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.xml': 'application/xml; charset=utf-8'}
for path in sorted((root / 'public').rglob('*')):
    if path.is_file():
        name = '/' + path.relative_to(root / 'public').as_posix()
        content_type = types.get(path.suffix, mimetypes.guess_type(path.name)[0] or 'application/octet-stream')
        assets[name] = {'type': content_type, 'data': base64.b64encode(path.read_bytes()).decode('ascii')}
snapshot = json.loads((root / 'latest-videos.json').read_text())
runtime = (root / 'worker/runtime.js').read_text()
(root / 'worker/index.js').write_text('// Generated by scripts/embed-assets.py; edit worker/runtime.js or public assets.\n' + runtime + '\nconst ASSETS = ' + json.dumps(assets, separators=(',', ':')) + ';\nconst SNAPSHOT = ' + json.dumps(snapshot, ensure_ascii=False) + ';\nexport default createWorker(ASSETS, SNAPSHOT);\n')
print(f'Embedded {len(assets)} assets in the Site Worker.')
